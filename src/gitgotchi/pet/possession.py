"""Spot commits written by AI coding agents."""
import re
from typing import Optional

# Agent identities as they appear in Co-Authored-By trailers and commit
# authors: noreply addresses and bot accounts. People who work at these
# companies, or happen to be called Claude, Devin or Cline, don't match.
IDENTITIES = [
    ("Claude", r"noreply@anthropic\.com|claude\[bot\]|^claude[ -](code|opus|sonnet|haiku|fable|mythos)\b"),
    ("Copilot", r"\+copilot@users\.noreply\.github\.com|copilot\[bot\]|copilot-swe-agent|^copilot\b"),
    ("Codex", r"noreply@openai\.com|codex\[bot\]|chatgpt-codex|^codex\b"),
    ("Cursor", r"cursoragent@cursor\.com|cursor\[bot\]|^cursor agent\b"),
    ("Devin", r"devin-ai-integration|devin\[bot\]|@devin\.ai"),
    ("Aider", r"noreply@aider\.chat|\(aider\)"),
    ("Gemini", r"gemini-code-assist|gemini\[bot\]|google-labs-jules|jules\[bot\]|^gemini cli\b"),
    ("Windsurf", r"windsurf\[bot\]|noreply@codeium\.com|noreply@windsurf\.com"),
    ("Cline", r"cline\[bot\]|noreply@cline\.bot"),
    ("Amp", r"amp@ampcode\.com"),
]

# Product names as they appear in "Generated with ..." footers
PRODUCTS = [
    ("Claude", r"claude"),
    ("Copilot", r"(github )?copilot"),
    ("Codex", r"codex|chatgpt"),
    ("Cursor", r"cursor"),
    ("Devin", r"devin"),
    ("Aider", r"aider"),
    ("Gemini", r"gemini|jules"),
    ("Windsurf", r"windsurf|codeium"),
    ("Cline", r"cline|roo ?code"),
    ("Amp", r"amp"),
]

TRAILER = re.compile(r"^\s*co-authored-by:\s*(?P<who>.+)$", re.IGNORECASE | re.MULTILINE)

# A footer line like "🤖 Generated with [Claude Code](...)". It has to start
# the line and name the product right away, so prose such as "remove code
# generated by ChatGPT" in a subject doesn't count.
FOOTER = re.compile(
    r"^\W*(generated|created|written|made|authored) (with|by|using) \[?"
    r"(?P<who>(" + "|".join(p for _, p in PRODUCTS) + r"))\b",
    re.IGNORECASE | re.MULTILINE,
)


def _identity(text: str) -> Optional[str]:
    text = text.strip()
    for name, pattern in IDENTITIES:
        if re.search(pattern, text, re.IGNORECASE):
            return name
    return None


def _product(text: str) -> Optional[str]:
    for name, pattern in PRODUCTS:
        if re.fullmatch(pattern, text, re.IGNORECASE):
            return name
    return None


def detect_agent(message: str, author_name: str = "", author_email: str = "") -> Optional[str]:
    """Name of the AI agent that wrote a commit, or None for a human commit.

    Looks at Co-Authored-By trailers, "Generated with ..." footers, and the
    author itself (agents like Aider and Copilot's coding agent commit under
    their own accounts).
    """
    for trailer in TRAILER.finditer(message):
        agent = _identity(trailer.group("who"))
        if agent:
            return agent

    body = message.split("\n", 1)[1] if "\n" in message else ""
    footer = FOOTER.search(body)
    if footer:
        agent = _product(footer.group("who"))
        if agent:
            return agent

    if message.lstrip().lower().startswith("aider:"):
        return "Aider"

    return _identity(author_name) or _identity(author_email)
