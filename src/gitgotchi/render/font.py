BITMAPS = {
    char: np.array([[c == "#" for c in row] for row in pattern.split("|")], bool)
    for char, pattern in GLYPHS.items()
}
UNKNOWN = BITMAPS["?"]
GLYPH_W, GLYPH_H = 5, 7


def text_width(text: str, scale: int = 1) -> int:
    return max(0, len(text) * (GLYPH_W + 1) - 1) * scale


def draw_text(image: np.ndarray, text: str, x: int, y: int, color, scale: int = 1, shadow=None) -> int:
    """Draw text onto an RGB(A) image in place. Returns the x after the text."""
    if shadow is not None:
        draw_text(image, text, x + scale, y + scale, shadow, scale)
    h, w = image.shape[:2]
    color = np.asarray(color, float)
    cursor = x
    for char in text.upper():
        bitmap = BITMAPS.get(char, UNKNOWN)
        if scale > 1:
            bitmap = bitmap.repeat(scale, 0).repeat(scale, 1)
        ys, xs = np.nonzero(bitmap)
        ys, xs = ys + y, xs + cursor
        keep = (ys >= 0) & (ys < h) & (xs >= 0) & (xs < w)
        image[ys[keep], xs[keep], : len(color)] = color
        cursor += (GLYPH_W + 1) * scale
    return cursor
